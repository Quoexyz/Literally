# 舌面音 j/q/x 不能直接与 e 相拼，需补介音：jet=杰特、check=切克
PALATAL_E = {"j": "jie", "q": "qie", "x": "xie"}


def resolve(initial: str, final: str) -> tuple[str, str] | None:
    """
    把 (声母, 韵母) 解析成一个汉语音译字。
    返回 (实际使用的拼音, 汉字)，实在解析不了返回 None。

    退化链路：
      1. 精确命中 initial+final
      2. 韵母按 _FALLBACK_FINALS 逐级简化后重试
      3. 声母退化：加一个中性元音 e / a
      4. 丢弃声母，只用韵母
    """
    # 1. 精确命中
    py = initial + final
    if py in PY2ZH:
        return py, PY2ZH[py]

    # 1b. j/q/x + e -> jie/qie/xie
    if final == "e" and initial in PALATAL_E:
        alt = PALATAL_E[initial]
        if alt in PY2ZH:
            return alt, PY2ZH[alt]

    # 2. 韵母简化
    for simpler in _FALLBACK_FINALS.get(final, [final]):
        if simpler == final:
            continue
        py = initial + simpler
        if py in PY2ZH:
            return py, PY2ZH[py]

    # 3. 声母 + 中性元音
    for neutral in ("e", "a", "o", "u", "i"):
        py = initial + neutral
        if py in PY2ZH:
            return py, PY2ZH[py]

    # 4. 只保留韵母
    if final in PY2ZH:
        return final, PY2ZH[final]
    for simpler in _FALLBACK_FINALS.get(final, [final]):
        if simpler in PY2ZH:
            return simpler, PY2ZH[simpler]

    return None
