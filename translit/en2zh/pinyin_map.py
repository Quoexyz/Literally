def lookup(syllable: str) -> str | None:
    """查拼音音节对应的汉字，找不到返回 None。"""
    return PY2ZH.get(syllable)


def alt_of(syllable: str) -> list[str]:
    """返回候选字列表（含首选字在最前）。"""
    main = PY2ZH.get(syllable)
    alts = PY2ALT.get(syllable, [])
    if main is None:
        return list(alts)
    out = [main]
    for a in alts:
        if a not in out:
            out.append(a)
    return out


